from candidate_profile.loader import CandidateProfile
from database.models import Application, ApplicationStatus, EmploymentType
from database.repository import ApplicationRepository
from duplicate_checker.deduplicator import DuplicateChecker, canonicalize_url
from job_matcher.scorer import JobScorer, DecisionBand
from job_parser.extractor import ParsedJob
from job_sources.permission_matrix import PlatformPermissionMatrix, PlatformMode
