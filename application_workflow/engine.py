from telegram_notifications.templates import (
    format_new_job_found,
    format_application_submitted,
    format_manual_action_required,
    format_daily_summary,
)
from .form_handler import ApplicationFormHandler

logger = logging.getLogger("workflow_engine")


@dataclass
class WorkflowExecutionSummary:
    total_discovered: int = 0
    total_qualified: int = 0
    total_rejected: int = 0
    high_priority_count: int = 0
    submitted_count: int = 0
    manual_action_count: int = 0
    duplicates_prevented: int = 0
    errors: List[str] = field(default_factory=list)


class ApplicationEngine:
    def __init__(
        self,
        profile: CandidateProfile,
        repository: ApplicationRepository,
        notifier: Optional[TelegramNotifier] = None,
        mode: str = "DISCOVERY_MODE",
        pre_activation_approved: bool = False,
        daily_application_limit: int = 10,
        output_dir: Optional[Path | str] = None,
    ):
        self.profile = profile
        self.repo = repository
        self.notifier = notifier or TelegramNotifier()
        self.mode = mode
        self.pre_activation_approved = pre_activation_approved
        self.daily_application_limit = daily_application_limit

        base_dir = Path(__file__).resolve().parent.parent
        self.output_dir = Path(output_dir) if output_dir else base_dir / "output"
        self.output_dir.mkdir(parents=True, exist_ok=True)

        self.matcher = JobScorer(self.profile)
        self.duplicate_checker = DuplicateChecker(self.repo)
        self.form_handler = ApplicationFormHandler(self.profile)
        self.permission_matrix = PlatformPermissionMatrix()

    def process_job(self, parsed_job: ParsedJob) -> Optional[Application]:
        """
        Execute the 13-Step Per-Job Execution Pipeline.
        """
        now_ts = datetime.utcnow().isoformat()
        canonical_url = canonicalize_url(parsed_job.job_url)

        # Step 1 & 2: Verify employer and title
        if not parsed_job.employer or not parsed_job.title:
            logger.warning("Skipping job with empty employer or title.")
            return None

        # Step 4: Compute 100-Point Score & Hard Veto
        score_result = self.matcher.evaluate_job(parsed_job)

        # Step 5: Duplicate Check
        dup_result = self.duplicate_checker.check_duplicate(
            employer=parsed_job.employer,
            job_title=parsed_job.title,
            location=parsed_job.location,
            raw_url=parsed_job.job_url,
            source_platform=parsed_job.source_platform,
            external_job_id=parsed_job.external_job_id,
        )

        if dup_result.is_duplicate:
            logger.info(f"Duplicate prevented: {dup_result.explanation}")
            return dup_result.existing_application

        # Initial Application Record
        app = Application(
            id="",  # Auto-generated by repo
            employer=parsed_job.employer,
            job_title=parsed_job.title,
            employment_type=parsed_job.employment_type,
            job_description_summary=parsed_job.summary,
            job_url=parsed_job.job_url,
            canonical_url=canonical_url,
            source_platform=parsed_job.source_platform,
            external_job_id=parsed_job.external_job_id,
            location=parsed_job.location,
            work_arrangement=parsed_job.work_arrangement,
            posting_date=parsed_job.posting_date,
            discovery_timestamp=now_ts,
            matching_score=score_result.total_score,
            matching_explanation_json=score_result.to_json(),
            required_skills_json=str(score_result.required_verified_skills).replace("'", '"'),
            missing_skills_json=str(score_result.missing_critical_skills).replace("'", '"'),
            selected_resume_version=score_result.recommended_resume_version,
            application_status=ApplicationStatus.DISCOVERED.value,
            is_synthetic=parsed_job.is_synthetic,
            verification_status=parsed_job.verification_status,
            salary_range=parsed_job.salary_range,
            min_experience_years=parsed_job.min_experience_years,
            date_discovered=now_ts,
            date_last_checked=now_ts,
        )

        # Handle Veto or Rejection
        if score_result.is_vetoed or score_result.total_score < 60:
            app.application_status = ApplicationStatus.REJECTED.value
            app.error_log = score_result.veto_reason or f"Score below 60 threshold ({score_result.total_score}/100)"
            return self.repo.add_application(app)

        # Job is Qualified
        app.application_status = ApplicationStatus.QUALIFIED.value
        app = self.repo.add_application(app)

        # Dispatch Template A (New Job Found) for any qualified opportunity (Score >= 60)
        new_job_msg = format_new_job_found(app, score_result)
        self.notifier.send_message(new_job_msg, event_id=f"new_job_{app.id}")

        # Mode 1: DISCOVERY_MODE stops here (Zero form filling, zero submissions)
        if self.mode == "DISCOVERY_MODE":
            return app

        # Step 6 & 7: Select & Generate Tailored Resume and Cover Letter
        docx_path = generate_docx_resume(self.profile, variant=score_result.recommended_resume_version, output_dir=self.output_dir / "resumes")
        pdf_path = generate_pdf_resume(self.profile, variant=score_result.recommended_resume_version, output_dir=self.output_dir / "resumes")
        cl_res = generate_cover_letter(self.profile, parsed_job, output_dir=self.output_dir / "cover_letters")
        app.cover_letter_path = cl_res.file_path

        # Check Platform Permissions
        platform_permits_auto = self.permission_matrix.is_auto_apply_permitted(parsed_job.source_platform)

        # Step 8 & 9: Form Data Preparation & Zero-Guessing Validation
        form_result = self.form_handler.prepare_and_validate_form(
            portal_manual_only=(not platform_permits_auto),
        )

        # Mode 2: ASSISTED_APPLICATION_MODE
        if self.mode == "ASSISTED_APPLICATION_MODE" or not platform_permits_auto:
            self.repo.update_status(
                application_id=app.id,
                new_status=ApplicationStatus.AWAITING_MANUAL_ACTION,
                reason_or_actor=form_result.halt_reason or "Assisted Application Mode: Manual Submission Required",
            )
            halt_reason = form_result.halt_reason or f"Platform '{parsed_job.source_platform}' requires manual submission."
            next_step = form_result.candidate_next_step or "Review pre-staged materials and submit application via link."

            manual_msg = format_manual_action_required(
                app=app,
                halt_reason=halt_reason,
                next_step=next_step,
                resume_path=pdf_path,
                cover_letter_path=cl_res.file_path,
            )
            self.notifier.send_message(manual_msg, event_id=f"manual_action_{app.id}")
            return app

        # Mode 3: AUTHORIZED_AUTO_APPLY_MODE
        if self.mode == "AUTHORIZED_AUTO_APPLY_MODE":
            # Safety Gate 1: Candidate Approval
            if not self.pre_activation_approved:
                self.repo.update_status(
                    application_id=app.id,
                    new_status=ApplicationStatus.AWAITING_MANUAL_ACTION,
                    reason_or_actor="Pre-Activation Approval Gate locked",
                )
                manual_msg = format_manual_action_required(
                    app=app,
                    halt_reason="PRE_ACTIVATION_APPROVAL_PENDING",
                    next_step="Mode 3 requires explicit candidate sign-off on Pre-Activation Configuration Summary.",
                    resume_path=pdf_path,
                    cover_letter_path=cl_res.file_path,
                )
                self.notifier.send_message(manual_msg, event_id=f"approval_gate_{app.id}")
                return app

            # Safety Gate 2: Daily Rate Limit Check
            today_submissions = self.repo.get_daily_submission_count()
            if today_submissions >= self.daily_application_limit:
                self.repo.update_status(
                    application_id=app.id,
                    new_status=ApplicationStatus.AWAITING_MANUAL_ACTION,
                    reason_or_actor=f"Daily limit reached ({today_submissions}/{self.daily_application_limit})",
                )
                manual_msg = format_manual_action_required(
                    app=app,
                    halt_reason="DAILY_CAP_REACHED",
                    next_step="Daily submission quota of 10 reached. Application queued for next cycle.",
                    resume_path=pdf_path,
                    cover_letter_path=cl_res.file_path,
                )
                self.notifier.send_message(manual_msg, event_id=f"cap_reached_{app.id}")
                return app

            # Safety Gate 3: Form Validation (Zero Guessing)
            if not form_result.can_auto_submit:
                self.repo.update_status(
                    application_id=app.id,
                    new_status=ApplicationStatus.AWAITING_MANUAL_ACTION,
                    reason_or_actor=form_result.halt_reason or "Missing mandatory fields",
                )
                manual_msg = format_manual_action_required(
                    app=app,
                    halt_reason=form_result.halt_reason or "Missing required field",
                    next_step=form_result.candidate_next_step or "Provide candidate data.",
                    resume_path=pdf_path,
                    cover_letter_path=cl_res.file_path,
                )
                self.notifier.send_message(manual_msg, event_id=f"form_halt_{app.id}")
                return app

            # Step 10 & 11: Auto-Submission & Confirmation
            # Transition to SUBMITTED
            self.repo.update_status(
                application_id=app.id,
                new_status=ApplicationStatus.SUBMITTED,
                reason_or_actor="Automated submission dispatched via compliant ATS interface",
            )
            # Record confirmed submission
            self.repo.update_status(
                application_id=app.id,
                new_status=ApplicationStatus.APPLICATION_CONFIRMED,
                reason_or_actor="ATS confirmation response received",
                submission_ref=f"ATS-REF-{app.id[:8].upper()}",
            )

            # Step 13: Dispatch Notification B
            updated_app = self.repo.get_application_by_id(app.id) or app
            sub_msg = format_application_submitted(updated_app, is_confirmed=True)
            self.notifier.send_message(sub_msg, event_id=f"submitted_{app.id}")

        return app

    def generate_daily_report(self) -> Dict[str, str]:
        """Generate both Markdown and CSV daily reports."""
        today_str = date.today().isoformat()
        reports_dir = self.output_dir / "reports"
        reports_dir.mkdir(parents=True, exist_ok=True)

        csv_file = reports_dir / f"Daily_Job_Report_{today_str}.csv"
        self.repo.export_to_csv(csv_file)

        kpis = self.repo.get_kpi_summary()
        apps = self.repo.get_applications(limit=100)

        md_file = reports_dir / f"Daily_Job_Report_{today_str}.md"
        with open(md_file, "w", encoding="utf-8") as f:
            f.write(f"# Daily Job Application Executive Report\n")
            f.write(f"**Date:** {today_str} | **Candidate:** {self.profile.full_name} | **Active Mode:** `{self.mode}`\n\n")
            f.write(f"## Key Performance Indicators\n")
            f.write(f"- **Total Opportunities Tracked:** {kpis.get('total_applications', 0)}\n")
            f.write(f"- **Full-Time Permanent Roles:** {kpis.get('full_time_count', 0)}\n")
            f.write(f"- **Internships / Trainee Roles:** {kpis.get('internship_count', 0)}\n")
            f.write(f"- **High-Priority Matches (≥85):** {kpis.get('high_priority_matches', 0)}\n")
            f.write(f"- **Applications Submitted Today:** {kpis.get('submitted_today', 0)} / {kpis.get('daily_limit', 10)}\n")
            f.write(f"- **Applications Awaiting Manual Action:** {kpis.get('awaiting_manual_action', 0)}\n\n")

            f.write(f"## Recent Opportunities Table\n\n")
            f.write(f"| Company | Job Title | Type | Location | Score | Status | Resume | Link |\n")
            f.write(f"| :--- | :--- | :--- | :--- | :--- | :--- | :--- | :--- |\n")
            for a in apps[:20]:
                f.write(
                    f"| {a.employer} | {a.job_title} | {a.employment_type} | {a.location} | "
                    f"**{a.matching_score}/100** | `{a.application_status}` | `{a.selected_resume_version}` | "
                    f"[View Job]({a.job_url}) |\n"
                )

        # Dispatch Daily Telegram Summary (Template D)
        summary_msg = format_daily_summary(kpis, report_link=str(md_file))
        self.notifier.send_message(summary_msg, event_id=f"daily_summary_{today_str}")

        return {"csv": str(csv_file), "md": str(md_file)}
